      '系统代理': l10n.networkSystemProxy,
      '虚拟网卡模式': l10n.networkTunMode,
    };
    final exact = core[source];
    if (exact != null) return exact;

    final localeIndex = switch (l10n.localeName) {
      'zh_TW' => 1,
      'ja' => 2,
      'ko' => 3,
      'fr' => 4,
      _ => 0,
    };
    var result = source;
    final phrases = _phrases.entries.toList()
      ..sort((a, b) => b.key.length.compareTo(a.key.length));
    for (final phrase in phrases) {
      if (result.contains(phrase.key)) {
        result = result.replaceAll(phrase.key, phrase.value[localeIndex]);
      }
    }
    if (localeIndex == 1) return _traditionalize(result);
    return _han.hasMatch(result) ? source : result;
